def t(key: str, locale: str | None = None, **kwargs: Any) -> str:
    """Translate a message key; falls back to zh then the key itself."""
    loc = (locale or DEFAULT_LOCALE).split("-")[0].lower()
    if loc not in SUPPORTED:
        loc = DEFAULT_LOCALE
    table = MESSAGES.get(key) or {}
    text = table.get(loc) or table.get(DEFAULT_LOCALE) or table.get("en") or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text
